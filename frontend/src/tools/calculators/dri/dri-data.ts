import type { DriAgeBand, DriSex } from './types';

export type NutrientKind = 'rda' | 'ai' | 'cdrr';

export interface NutrientSpec {
  id: string;
  label: string;
  unit: string;
  kind: NutrientKind;
  /** Amount by [sex][ageBand]. */
  values: Record<DriSex, Record<DriAgeBand, number>>;
}

