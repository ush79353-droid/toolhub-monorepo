'use client';

import * as React from 'react';
import { Button } from '@/components/ui/button';
import type { ToolComponentProps } from '@/tools/types';
import { copyTextToClipboard } from '@/tools/shared/clipboard';
import { SortinoRatioForm } from './SortinoRatioForm';
import {
  createDefaultInput,
  type SortinoRatioFieldErrors,
  type SortinoRatioInput,
  type SortinoRatioResult,
} from './types';
import { validateSortinoRatioInput } from './validation';

export function SortinoRatioCalculator({
  metadata,
  className = '',
  presentation = 'default',
  headerActions,
}: ToolComponentProps) {
  const isEmbed = presentation === 'embed';
  const [input, setInput] = React.useState<SortinoRatioInput>(() => createDefaultInput());
  const [errors, setErrors] = React.useState<SortinoRatioFieldErrors>({});
  const [result, setResult] = React.useState<SortinoRatioResult | null>(null);
  const [copied, setCopied] = React.useState(false);
  const [shared, setShared] = React.useState(false);
  const [canShare, setCanShare] = React.useState(false);

  React.useEffect(() => {
    setCanShare(typeof navigator.share === 'function');
  }, []);

  const handleChange = (next: SortinoRatioInput) => {
    setInput(next);
    const validation = validateSortinoRatioInput(next);
    setErrors(validation.errors);
    setResult(validation.result);
  };

  const handleReset = () => {
    setInput(createDefaultInput());
    setErrors({});
    setResult(null);
  };

  const hasResult = Boolean(result?.asset1 || result?.asset2);
  const summary = hasResult
    ? [
        `${metadata.title} — Omega Calculators`,
        `Risk-free rate: ${input.riskFreeRate}%`,
        result?.asset1
          ? `Asset #1: Ra ${input.asset1.averageReturn}%, downside ${input.asset1.downsideDeviation}, Sortino ${result.asset1.formattedSortinoRatio}`
          : null,
        result?.asset2
          ? `Asset #2: Ra ${input.asset2.averageReturn}%, downside ${input.asset2.downsideDeviation}, Sortino ${result.asset2.formattedSortinoRatio}`
          : null,
      ]
        .filter(Boolean)
        .join('\n')
    : '';

  return (
    <section
      aria-label={`${metadata.title} calculator panel`}
      className={`overflow-hidden rounded-2xl border border-border bg-white ${
        isEmbed ? 'shadow-sm' : 'shadow-[0_12px_40px_-16px_rgba(22,60,67,0.28)]'
      } ${className}`}
    >
      <div className="flex flex-wrap items-center justify-between gap-2.5 border-b border-border bg-muted/45 px-4 py-3 sm:px-5">
        <div>
          <h2 className="text-[15px] font-semibold text-accent">Calculator</h2>
          <p className="text-xs font-normal text-muted-foreground">
            Sortino = (Ra − Rf) ÷ downside deviation
          </p>
        </div>
        {headerActions ? <div className="flex items-center gap-2">{headerActions}</div> : null}
      </div>

      <div className="space-y-4 p-4 sm:p-5">
        <SortinoRatioForm
          input={input}
          errors={errors}
          result={result}
          onChange={handleChange}
          onReset={handleReset}
        />
        <div className="flex flex-wrap gap-2">
          <Button
            type="button"
            variant="outline"
            className="h-9 px-3 text-xs font-medium"
            disabled={!summary}
            onClick={async () => {
              if (!summary) return;
              if (await copyTextToClipboard(summary)) {
                setCopied(true);
                window.setTimeout(() => setCopied(false), 2000);
              }
            }}
          >
            {copied ? 'Copied' : 'Copy results'}
          </Button>
          {canShare ? (
            <Button
              type="button"
              variant="outline"
              className="h-9 px-3 text-xs font-medium"
              disabled={!summary}
              onClick={async () => {
                if (!summary) return;
                try {
                  await navigator.share({ title: metadata.title, text: summary });
                  setShared(true);
                  window.setTimeout(() => setShared(false), 2000);
                } catch {
                  // dismissed
                }
              }}
            >
              {shared ? 'Shared' : 'Share'}
            </Button>
          ) : null}
        </div>
      </div>
    </section>
  );
}
