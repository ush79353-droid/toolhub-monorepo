'use client';

import type { ReactNode } from 'react';
import { useState } from 'react';
import { ChevronDown } from 'lucide-react';
import { Button } from '@/components/ui/button';
import { CurrencySelect } from '@/tools/shared/CurrencySelect';
import { getCurrencySymbol, type SupportedCurrency } from '@/tools/shared/currency';
import { InfoTooltip } from '../auto-loan/InfoTooltip';
import { formatEvaMoney } from './calculation';
import type { EvaFieldErrors, EvaInput, EvaResult } from './types';

const labelClass =
  'mb-1.5 flex items-center gap-1.5 text-[13px] font-medium text-accent';
const inputClass =
  'h-11 w-full min-w-0 bg-transparent px-3 text-sm tabular-nums text-accent outline-none';

function FieldShell({
  error,
  muted,
  children,
}: {
  error?: string;
  muted?: boolean;
  children: ReactNode;
}) {
  return (
    <div
      className={`relative flex h-11 min-w-0 flex-1 items-center rounded-lg border focus-within:ring-2 focus-within:ring-ring ${
        muted ? 'border-border bg-muted/30' : 'border-border bg-white'
      } ${error ? 'border-rose-400' : ''}`}
    >
      {children}
    </div>
  );
}

interface EvaFormProps {
  input: EvaInput;
  errors: EvaFieldErrors;
  result: EvaResult | null;
  helperInvestedCapital: number | null;
  onChange: (input: EvaInput) => void;
  onCurrencyChange: (next: SupportedCurrency) => void;
  onApplyHelperCapital: () => void;
}

export function EvaForm({
  input,
  errors,
  result,
  helperInvestedCapital,
  onChange,
  onCurrencyChange,
  onApplyHelperCapital,
}: EvaFormProps) {
  const [helperOpen, setHelperOpen] = useState(false);
  const symbol = getCurrencySymbol(input.currency);

  return (
    <form
      onSubmit={(e) => e.preventDefault()}
      className="space-y-4"
      noValidate
      autoComplete="off"
    >
      <p className="rounded-lg border border-border bg-muted/20 px-3 py-2.5 text-xs leading-relaxed text-muted-foreground">
        EVA = NOPAT − (Invested capital × WACC). Enter WACC as a percent; the
        capital charge uses the decimal form.
      </p>

      <div className="flex flex-wrap items-center justify-between gap-2">
        <span className="text-[13px] font-medium text-accent">Currency</span>
        <CurrencySelect
          id="eva-currency"
          value={input.currency}
          onChange={onCurrencyChange}
          aria-label="Currency for EVA amounts"
        />
      </div>
      <p className="text-xs text-muted-foreground">
        Money fields share one currency label (denomination only — no FX).
      </p>
      <p className="text-xs">
        <a
          href="#how-to-use"
          className="font-medium text-primary underline-offset-2 hover:underline"
        >
          How to use the EVA calculator
        </a>
      </p>

      <fieldset className="space-y-3.5 rounded-xl border border-border bg-muted/15 p-3.5 sm:p-4">
        <legend className="px-1 text-[13px] font-semibold text-accent">
          Economic value added
        </legend>

        <div>
          <label htmlFor="eva-nopat" className={labelClass}>
            NOPAT
            <InfoTooltip
              label="NOPAT"
              text="Net operating profit after taxes, calculated before financing costs. It represents the after-tax profit generated by operations."
            />
          </label>
          <FieldShell error={errors.nopat}>
            <span className="pl-3 text-sm text-muted-foreground" aria-hidden>
              {symbol}
            </span>
            <input
              id="eva-nopat"
              type="text"
              inputMode="decimal"
              className={inputClass}
              value={input.nopat}
              onChange={(e) => onChange({ ...input, nopat: e.target.value })}
              placeholder="750,000"
              aria-invalid={Boolean(errors.nopat)}
            />
          </FieldShell>
          {errors.nopat ? (
            <p className="mt-1 text-xs text-rose-600">{errors.nopat}</p>
          ) : null}
        </div>

        <div>
          <label htmlFor="eva-ic" className={labelClass}>
            Invested capital
            <InfoTooltip
              label="Invested capital"
              text="Capital invested in the company's operating activities, typically calculated using an appropriate operating-assets-and-liabilities or financing-capital approach."
            />
          </label>
          <FieldShell error={errors.investedCapital}>
            <span className="pl-3 text-sm text-muted-foreground" aria-hidden>
              {symbol}
            </span>
            <input
              id="eva-ic"
              type="text"
              inputMode="decimal"
              className={inputClass}
              value={input.investedCapital}
              onChange={(e) =>
                onChange({ ...input, investedCapital: e.target.value })
              }
              placeholder="1,000,000"
              aria-invalid={Boolean(errors.investedCapital)}
            />
          </FieldShell>
          {errors.investedCapital ? (
            <p className="mt-1 text-xs text-rose-600">{errors.investedCapital}</p>
          ) : null}
        </div>

        <div>
          <label htmlFor="eva-wacc" className={labelClass}>
            WACC
            <InfoTooltip
              label="WACC"
              text="The weighted average cost of capital, expressed as a percentage. It represents the required return on the capital invested in the company."
            />
          </label>
          <FieldShell error={errors.waccPercent}>
            <input
              id="eva-wacc"
              type="text"
              inputMode="decimal"
              className={inputClass}
              value={input.waccPercent}
              onChange={(e) =>
                onChange({ ...input, waccPercent: e.target.value })
              }
              placeholder="10"
              aria-invalid={Boolean(errors.waccPercent)}
            />
            <span className="pr-3 text-sm text-muted-foreground" aria-hidden>
              %
            </span>
          </FieldShell>
          {errors.waccPercent ? (
            <p className="mt-1 text-xs text-rose-600">{errors.waccPercent}</p>
          ) : null}
        </div>

        <div>
          <label htmlFor="eva-result" className={labelClass}>
            Economic value added
            <InfoTooltip
              label="Economic value added"
              text="EVA = NOPAT − (Invested capital × WACC). Positive values mean operating profit exceeds the capital charge."
            />
          </label>
          <FieldShell muted>
            <span className="pl-3 text-sm text-muted-foreground" aria-hidden>
              {symbol}
            </span>
            <input
              id="eva-result"
              type="text"
              readOnly
              tabIndex={-1}
              className={`${inputClass} cursor-default font-semibold text-accent`}
              value={result?.formattedEva.replace(symbol, '') ?? ''}
              placeholder="—"
              aria-readonly="true"
              aria-label={
                result
                  ? `Economic value added ${result.formattedEva}`
                  : 'Economic value added unavailable'
              }
            />
          </FieldShell>
        </div>
      </fieldset>

      <fieldset className="rounded-xl border border-border bg-muted/15">
        <legend className="sr-only">Calculate invested capital</legend>
        <button
          type="button"
          className="flex w-full items-center justify-between gap-2 px-3.5 py-3 text-left text-[13px] font-semibold text-accent sm:px-4"
          aria-expanded={helperOpen}
          onClick={() => setHelperOpen((v) => !v)}
        >
          <span>Calculate invested capital</span>
          <ChevronDown
            className={`h-4 w-4 shrink-0 text-primary transition-transform ${
              helperOpen ? 'rotate-180' : ''
            }`}
            aria-hidden
          />
        </button>
        {helperOpen ? (
          <div className="space-y-3.5 border-t border-border px-3.5 py-3.5 sm:px-4 sm:py-4">
            <p className="text-xs leading-relaxed text-muted-foreground">
              Operating assets − operating liabilities. Click “Use calculated
              invested capital” to copy the result into the main field (manual
              entries are not overwritten automatically).
            </p>

            <div>
              <label htmlFor="eva-oa" className={labelClass}>
                Operating assets
              </label>
              <FieldShell error={errors.operatingAssets}>
                <span className="pl-3 text-sm text-muted-foreground" aria-hidden>
                  {symbol}
                </span>
                <input
                  id="eva-oa"
                  type="text"
                  inputMode="decimal"
                  className={inputClass}
                  value={input.operatingAssets}
                  onChange={(e) =>
                    onChange({ ...input, operatingAssets: e.target.value })
                  }
                  placeholder="2,500,000"
                  aria-invalid={Boolean(errors.operatingAssets)}
                />
              </FieldShell>
              {errors.operatingAssets ? (
                <p className="mt-1 text-xs text-rose-600">
                  {errors.operatingAssets}
                </p>
              ) : null}
            </div>

            <div>
              <label htmlFor="eva-ol" className={labelClass}>
                Operating liabilities
              </label>
              <FieldShell error={errors.operatingLiabilities}>
                <span className="pl-3 text-sm text-muted-foreground" aria-hidden>
                  {symbol}
                </span>
                <input
                  id="eva-ol"
                  type="text"
                  inputMode="decimal"
                  className={inputClass}
                  value={input.operatingLiabilities}
                  onChange={(e) =>
                    onChange({
                      ...input,
                      operatingLiabilities: e.target.value,
                    })
                  }
                  placeholder="700,000"
                  aria-invalid={Boolean(errors.operatingLiabilities)}
                />
              </FieldShell>
              {errors.operatingLiabilities ? (
                <p className="mt-1 text-xs text-rose-600">
                  {errors.operatingLiabilities}
                </p>
              ) : null}
            </div>

            <div>
              <label htmlFor="eva-ic-calc" className={labelClass}>
                Calculated invested capital
              </label>
              <FieldShell muted>
                <span className="pl-3 text-sm text-muted-foreground" aria-hidden>
                  {symbol}
                </span>
                <input
                  id="eva-ic-calc"
                  type="text"
                  readOnly
                  tabIndex={-1}
                  className={`${inputClass} cursor-default text-muted-foreground`}
                  value={
                    helperInvestedCapital != null
                      ? formatEvaMoney(helperInvestedCapital, input.currency)
                      : ''
                  }
                  placeholder="—"
                  aria-readonly="true"
                />
              </FieldShell>
              {errors.investedCapitalHelper ? (
                <p className="mt-1 text-xs text-rose-600">
                  {errors.investedCapitalHelper}
                </p>
              ) : null}
            </div>

            <Button
              type="button"
              variant="outline"
              className="h-10 w-full justify-center rounded-xl border-border text-xs font-semibold text-accent hover:bg-muted/30"
              disabled={helperInvestedCapital == null}
              onClick={onApplyHelperCapital}
            >
              Use calculated invested capital
            </Button>
          </div>
        ) : null}
      </fieldset>

      {errors.form ? (
        <p className="text-xs text-rose-700" role="alert">
          {errors.form}
        </p>
      ) : null}
    </form>
  );
}
