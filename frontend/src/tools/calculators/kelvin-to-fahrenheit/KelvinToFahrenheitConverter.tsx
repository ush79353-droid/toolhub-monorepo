'use client';

import * as React from 'react';
import type { ToolComponentProps } from '@/tools/types';
import { copyTextToClipboard } from '@/tools/shared/clipboard';
import {
  calculateKelvinToFahrenheit,
  formatTemp,
  shareResultText,
  type KelvinToFahrenheitResult,
} from './calculation';
import {
  KelvinToFahrenheitForm,
  draftToInput,
  emptyDraft,
  type KelvinToFahrenheitDraft,
} from './KelvinToFahrenheitForm';
import { KelvinToFahrenheitResults } from './KelvinToFahrenheitResults';
import type { KelvinToFahrenheitFieldErrors } from './types';
import { isIncompleteNumber, validateKelvinToFahrenheit } from './validation';

function syncDraftFromResult(
  draft: KelvinToFahrenheitDraft,
  result: KelvinToFahrenheitResult,
): KelvinToFahrenheitDraft {
  if (draft.source === 'kelvin') {
    return { ...draft, fahrenheit: formatTemp(result.fahrenheit) };
  }
  return { ...draft, kelvin: formatTemp(result.kelvin) };
}

function clearOpposite(draft: KelvinToFahrenheitDraft): KelvinToFahrenheitDraft {
  if (draft.source === 'kelvin') return { ...draft, fahrenheit: '' };
  return { ...draft, kelvin: '' };
}

export function KelvinToFahrenheitConverter({
  metadata,
  className = '',
  presentation = 'default',
  headerActions,
}: ToolComponentProps) {
  const isEmbed = presentation === 'embed';
  const [draft, setDraft] = React.useState<KelvinToFahrenheitDraft>(emptyDraft);
  const [errors, setErrors] = React.useState<KelvinToFahrenheitFieldErrors>({});
  const [result, setResult] = React.useState<KelvinToFahrenheitResult | null>(null);
  const [copied, setCopied] = React.useState(false);
  const [shared, setShared] = React.useState(false);
  const [canShare, setCanShare] = React.useState(false);

  React.useEffect(() => {
    setCanShare(typeof navigator.share === 'function');
  }, []);

  const evaluate = (next: KelvinToFahrenheitDraft) => {
    const sourceRaw = next.source === 'kelvin' ? next.kelvin : next.fahrenheit;
    if (sourceRaw.trim() === '' || isIncompleteNumber(sourceRaw.trim().replace(/,/g, ''))) {
      setErrors({});
      setResult(null);
      setDraft(clearOpposite(next));
      return;
    }

    const input = draftToInput(next);
    const validation = validateKelvinToFahrenheit(input);
    setErrors(validation.errors);
    if (!validation.isValid) {
      setResult(null);
      setDraft(next);
      return;
    }
    const nextResult = calculateKelvinToFahrenheit(input);
    setResult(nextResult);
    setDraft(syncDraftFromResult(next, nextResult));
  };

  const payload = result ? shareResultText(result) : '';

  return (
    <section
      aria-label={`${metadata.title} calculator panel`}
      className={`overflow-hidden rounded-2xl border border-border bg-white ${
        isEmbed ? 'shadow-sm' : 'shadow-[0_12px_40px_-16px_rgba(22,60,67,0.28)]'
      } ${className}`}
    >
      <div className="flex flex-wrap items-center justify-between gap-2.5 border-b border-border bg-muted/45 px-4 py-3 sm:px-5">
        <div>
          <h2 className="text-[15px] font-semibold text-accent">Calculator</h2>
          <p className="text-xs font-normal text-muted-foreground">
            °F = (K − 273.15) × 9/5 + 32
          </p>
        </div>
        {headerActions ? <div className="flex flex-wrap justify-end gap-2">{headerActions}</div> : null}
      </div>
      <div className="space-y-4 p-4 sm:p-5">
        <KelvinToFahrenheitForm
          draft={draft}
          errors={errors}
          onDraftChange={evaluate}
          onSubmit={(event) => {
            event.preventDefault();
            evaluate(draft);
          }}
          onReload={() => {
            setDraft(emptyDraft());
            setErrors({});
            setResult(null);
            setCopied(false);
            setShared(false);
          }}
          onReset={() => {
            setDraft(emptyDraft());
            setErrors({});
            setResult(null);
            setCopied(false);
            setShared(false);
          }}
        >
          <KelvinToFahrenheitResults
            result={result}
            invalid={Object.keys(errors).length > 0}
            copied={copied}
            shared={shared}
            canShare={canShare || Boolean(result)}
            onCopy={() => {
              if (!result) return;
              const text =
                typeof window !== 'undefined'
                  ? `${payload}\n\n${window.location.href}`
                  : payload;
              void copyTextToClipboard(text).then((ok) => {
                if (!ok) return;
                setCopied(true);
                window.setTimeout(() => setCopied(false), 2000);
              });
            }}
            onShare={() => {
              if (!result) return;
              const text =
                typeof window !== 'undefined'
                  ? `${payload}\n\n${window.location.href}`
                  : payload;
              if (typeof navigator.share === 'function') {
                void navigator
                  .share({
                    title: metadata.title,
                    text,
                    url: typeof window !== 'undefined' ? window.location.href : undefined,
                  })
                  .then(() => {
                    setShared(true);
                    window.setTimeout(() => setShared(false), 2000);
                  })
                  .catch(() => {
                    void copyTextToClipboard(text).then((ok) => {
                      if (!ok) return;
                      setCopied(true);
                      window.setTimeout(() => setCopied(false), 2000);
                    });
                  });
                return;
              }
              void copyTextToClipboard(text).then((ok) => {
                if (!ok) return;
                setShared(true);
                window.setTimeout(() => setShared(false), 2000);
              });
            }}
          />
        </KelvinToFahrenheitForm>
      </div>
    </section>
  );
}
